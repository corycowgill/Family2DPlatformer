/** Glyph advance for a space character. */
export const SPACE_WIDTH = 3;

export interface Glyph {
  ch: string;
  width: number;
  /** rows[y][x] — always GLYPH_ROWS rows. */
  rows: boolean[][];
}

export function parseGlyph(ch: string, src: string): Glyph {
  const lines = src.split('|');
  const width = Math.max(...lines.map((l) => l.length));
  if (lines.length !== CAP_HEIGHT && lines.length !== GLYPH_ROWS) {
    throw new Error(`Glyph "${ch}" has ${lines.length} rows`);
  }
  const rows: boolean[][] = [];
  for (let y = 0; y < GLYPH_ROWS; y++) {
    const line = lines[y] ?? '';
    rows.push(Array.from({ length: width }, (_, x) => line[x] === '#'));
  }
  return { ch, width, rows };
}

let cache: Glyph[] | null = null;
export function allGlyphs(): Glyph[] {
  if (!cache) cache = Object.entries(G).map(([ch, src]) => parseGlyph(ch, src));
  return cache;
}

export const SUPPORTED_CHARS = new Set([' ', ...Object.keys(G)]);

const REPLACEMENTS: Record<string, string> = {
  '…': '...', '—': '-', '–': '-', '‘': "'", '’': "'", '“': '"', '”': '"', '■': '●', '□': '○', '✔': '✓', '♡': '♥', '☆': '★', '\t': ' ',
};

/** Map unsupported characters to something the font can draw. */
export function sanitizeText(s: string): string {
  let out = '';
  for (const ch of s) {
    if (ch === '\n' || SUPPORTED_CHARS.has(ch)) out += ch;
    else if (REPLACEMENTS[ch] !== undefined) out += REPLACEMENTS[ch];
    else if (SUPPORTED_CHARS.has(ch.toUpperCase())) out += ch.toUpperCase();
    else out += '?';
  }
  return out;
}

/** Width in font pixels of a single line (advance = glyph width + 1, no trailing gap). */
export function measureLine(s: string): number {
  const glyphs = new Map(allGlyphs().map((g) => [g.ch, g.width]));
  let w = 0;
  for (const ch of sanitizeText(s)) {
    if (ch === '\n') break;
    w += (ch === ' ' ? SPACE_WIDTH : glyphs.get(ch) ?? 0) + 1;
  }
  return Math.max(0, w - 1);
}
